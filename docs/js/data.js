// ── Helpers ───────────────────────────────────
function _genDates(n, endDate) {
  const d = endDate ? new Date(endDate) : new Date('2026-03-09');
  const out = [];
  for (let i = n - 1; i >= 0; i--) {
    const dt = new Date(d);
    dt.setDate(dt.getDate() - i);
    out.push(dt.toISOString().slice(0, 10));
  }
  return out;
}

function _randWalk(start, n, vol) {
  const arr = [start];
  for (let i = 1; i < n; i++) {
    const chg = (Math.random() - 0.48) * vol;
    arr.push(Math.round(arr[i - 1] * (1 + chg)));
  }
  return arr;
}

